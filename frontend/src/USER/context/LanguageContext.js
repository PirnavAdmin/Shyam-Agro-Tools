const translateProductFallback = (product, field, language, categoryName) => {
  if (language === 'en') return product[field] || '';
  const nameKey = String(product.name || '').trim().toUpperCase();
  const translatedName = productTermTranslations[language]?.[nameKey] || product.name;
  if (field === 'name') return translatedName;
  const template = productFieldTemplates[language]?.[field];
  return template ? template(translatedName, categoryName) : product[field] || translatedName;
};

const isCorruptTranslation = (value) =>
  typeof value === 'string' && (/\?{2,}/.test(value) || value.startsWith('?'));

const cleanTranslation = (value, fallback = '') =>
  value && !isCorruptTranslation(value) ? value : fallback;

const getByPath = (source, path) => {
  if (!source || !path) return undefined;
  return path.split('.').reduce((current, part) => current?.[part], source);
};

const getProductKeyForField = (field) => {
  const normalizedField = field === 'shortDescription' ? 'shortDesc' : field;
  return `${normalizedField}Key`;
};

const getLocalizedFieldValue = (source, field, language) => {
  if (!source || !field || language === 'en') return '';
  const raw = source.raw || {};
  const aliases = field === 'shortDesc'
    ? ['shortDesc', 'shortDescription']
    : field === 'longDesc'
      ? ['longDesc', 'description', 'productDetails']
      : field === 'description'
        ? ['description', 'productDetails', 'longDesc']
        : [field];

  for (const alias of aliases) {
    const candidates = [
      `${alias}_${language}`,
      `${alias}${language.toUpperCase()}`,
      `${alias}${language.charAt(0).toUpperCase()}${language.slice(1)}`,
      `${alias}_${language.toUpperCase()}`,
    ];

    for (const key of candidates) {
      const value = source[key] ?? raw[key];
      if (value && !isCorruptTranslation(value)) return value;
    }
  }

  const translationsBlock = source.translations || raw.translations || source.i18n || raw.i18n;
  for (const alias of aliases) {
    const value = translationsBlock?.[language]?.[alias] || translationsBlock?.[alias]?.[language];
    if (value && !isCorruptTranslation(value)) return value;
  }

  return '';
};

const getLocalizedListValue = (source, field, index, language) => {
  const value = getLocalizedFieldValue(source, field, language);
  if (Array.isArray(value)) return value[index] || '';
  if (typeof value === 'string') {
    return value
      .split(/\r?\n|,/)
      .map((item) => item.trim())
      .filter(Boolean)[index] || '';
  }
  return '';
};

const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [language, setLanguageState] = useState(() => {
    const savedLanguage = localStorage.getItem(STORAGE_KEY);
    return languages.some((item) => item.code === savedLanguage) ? savedLanguage : 'en';
  });

  const setLanguage = (code) => {
    const nextLanguage = languages.some((item) => item.code === code) ? code : 'en';
    localStorage.setItem(STORAGE_KEY, nextLanguage);
    setLanguageState(nextLanguage);
  };

  useEffect(() => {
    const direction = RTL_LANGUAGES.has(language) ? 'rtl' : 'ltr';
    document.documentElement.setAttribute('lang', language);
    document.documentElement.setAttribute('dir', direction);
    document.body.setAttribute('dir', direction);

    return () => {
      document.body.removeAttribute('dir');
    };
  }, [language]);

  const value = useMemo(() => {
    const activeLanguage = languages.find((item) => item.code === language) || languages[0];

    const t = (key) =>
      cleanTranslation(
        getByPath(translations[language], key) ?? translations[language]?.[key],
        (getByPath(translations.en, key) ?? translations.en[key]) || key
      );

    const getLocalizedCategoryName = (categoryName) => {
      if (!categoryName) return '';
      let categoryId = CATEGORY_ID_BY_ENGLISH_NAME[categoryName];
      if (!categoryId) {
        // Fallback: generate slug from name
        categoryId = String(categoryName).toLowerCase()
          .replace(/ & /g, '-and-')
          .replace(/&/g, '-and-')
          .replace(/ /g, '-')
          .replace(/\//g, '-')
          .replace(/\\/g, '-')
          .trim('-');
      }
      return categoryTranslations[language]?.[categoryId]?.name || categoryName;
    };

    const productText = (product, field = 'name') => {
      if (!product) return '';
      const keyField = getProductKeyForField(field);
      const localeProductText = product[keyField] ? getByPath(translations[language], product[keyField]) : '';
      if (localeProductText && !isCorruptTranslation(localeProductText)) return localeProductText;
      const englishProductText = product[keyField] ? getByPath(translations.en, product[keyField]) : '';
      if (language === 'en' && englishProductText) return englishProductText;
      const localizedFieldValue = getLocalizedFieldValue(product, field, language);
      if (localizedFieldValue) return localizedFieldValue;
      const manualTranslation = productTranslations[language]?.[product.id]?.[field];
      if (manualTranslation && !isCorruptTranslation(manualTranslation)) return manualTranslation;
      const knownTranslation = translateKnownDynamicText(product[field], language);
      if (knownTranslation) return knownTranslation;
      if (['description', 'longDesc', 'shortDesc', 'shortDescription', 'aboutProduct', 'productWork'].includes(field)) {
        return product[field] || '';
      }
      const categoryName = getLocalizedCategoryName(product.category);
      return cleanTranslation(
        translateProductFallback(product, field, language, categoryName),
        product[field] || product.name || ''
      );
    };

    const categoryText = (category, field = 'name') => {
      if (!category) return '';
      const keyField = getProductKeyForField(field);
      const keyedTranslation = category[keyField] ? t(category[keyField]) : '';
      if (keyedTranslation && keyedTranslation !== category[keyField]) return keyedTranslation;
      return cleanTranslation(
        categoryTranslations[language]?.[category.id]?.[field] ||
        categoryTranslations[language]?.[category.slug]?.[field],
        category[field] || ''
      );
    };

    const subcategoryText = (subcategory) => {
      if (!subcategory) return '';
      const key = subcategory.nameKey || subcategory.subCategoryKey;
      const keyedTranslation = key ? t(key) : '';
      if (keyedTranslation && keyedTranslation !== key) return keyedTranslation;
      return subcategoryTranslations[language]?.[subcategory.name] || subcategory.name || '';
    };

    const dynamicText = (source, field, fallback = '') => {
      const value = source?.[field] ?? fallback ?? '';
      if (!value) return '';
      if (language === 'en') return String(value);

      const fieldRoot = field
        .replace(/Name$/, '')
        .replace(/Text$/, '')
        .replace(/Description$/, 'Description');
      const fieldPascal = field.charAt(0).toUpperCase() + field.slice(1);
      const fieldRootPascal = fieldRoot.charAt(0).toUpperCase() + fieldRoot.slice(1);
      const localeKeys = [
        `${field}_${language}`,
        `${field}${language.toUpperCase()}`,
        `${field}${language.charAt(0).toUpperCase()}${language.slice(1)}`,
        `${fieldPascal}_${language}`,
        `${fieldPascal}${language.toUpperCase()}`,
        `${fieldPascal}${language.charAt(0).toUpperCase()}${language.slice(1)}`,
        `${fieldRoot}_${language}`,
        `${fieldRoot}${language.toUpperCase()}`,
        `${fieldRoot}${language.charAt(0).toUpperCase()}${language.slice(1)}`,
        `${fieldRootPascal}_${language}`,
        `${fieldRootPascal}${language.toUpperCase()}`,
        `${fieldRootPascal}${language.charAt(0).toUpperCase()}${language.slice(1)}`,
      ];

      const raw = source?.raw || {};
      for (const key of localeKeys) {
        const localized = source?.[key] ?? raw?.[key];
        if (localized && !isCorruptTranslation(localized)) return String(localized);
      }

      const translationsBlock = source?.translations || raw?.translations || source?.i18n || raw?.i18n;
      const localizedFromBlock = translationsBlock?.[language]?.[field] || translationsBlock?.[field]?.[language];
      if (localizedFromBlock && !isCorruptTranslation(localizedFromBlock)) return String(localizedFromBlock);

      const mapped = getDynamicTextTranslation(value, language);
      return mapped || String(value);
    };

    const productGenericText = (templateKey, values = {}, fallback = '') => {
      const template = t(`productGeneric.${templateKey}`);
      if (!template || template === `productGeneric.${templateKey}`) return fallback;
      return interpolate(template, values);
    };

    const productListText = (product, field, text, index = 0) => {
      if (!product) return text || '';
      const exactKey = `${product.translationBaseKey || `products.${product.id}`}.${field}.${index}`;
      const exactTranslation = getByPath(translations[language], exactKey);
      if (exactTranslation && !isCorruptTranslation(exactTranslation)) return exactTranslation;
      if (language === 'en') return text || '';
      const localizedListValue = getLocalizedListValue(product, field, index, language);
      if (localizedListValue && !isCorruptTranslation(localizedListValue)) return localizedListValue;
      const knownTranslation = translateKnownDynamicText(text, language);
      if (knownTranslation) return knownTranslation;

      if (field === 'productDetails' && text === product.aboutProduct) return productText(product, 'aboutProduct');
      if (field === 'productDetails' && text === product.productWork) return productText(product, 'productWork');
      return text || '';
    };

    const productSpecLabel = (key) => {
      const translated = t(`specLabels.${key}`);
      return translated && translated !== `specLabels.${key}` ? translated : formatReadableKey(key);
    };

    const productSpecValue = (product, key, value) => {
      if (language === 'en') return value || '';
      const exactKey = `${product?.specificationsKey || `products.${product?.id}.specifications`}.${key}`;
      const exactTranslation = getByPath(translations[language], exactKey);
      if (exactTranslation && !isCorruptTranslation(exactTranslation)) return exactTranslation;
      const localizedSpec = getLocalizedFieldValue(product?.specifications || product, key, language);
      const knownTranslation = translateKnownDynamicText(value, language);
      return localizedSpec || knownTranslation || value || '';
    };

    const reviewText = (product, review, field = 'comment') => {
      if (!review) return '';
      if (field === 'userName') return review.userName || '';
      if (language === 'en') return review[field] || '';
      return productGenericText(
        'reviewComment',
        {
          productName: productText(product, 'name'),
          rating: review.rating || 5,
        },
        review[field] || ''
      );
    };

    return {
      language,
      activeLanguage,
      languages,
      setLanguage,
      t,
      productText,
      productListText,
      productSpecLabel,
      productSpecValue,
      reviewText,
      categoryText,
      subcategoryText,
      dynamicText,
    };
  }, [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
};

export const useLanguage = () => useContext(LanguageContext);
